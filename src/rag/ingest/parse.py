"""Step 2 of the pipeline: turn a messy arXiv web page into clean text, organized by section.

arXiv's HTML is generated by a tool called LaTeXML, which tags every piece of the paper with a
class name (ltx_para = paragraph, ltx_bibliography = reference list, ...). We use those tags to
keep the paper's real content and drop everything else.

Run it:  PYTHONPATH=src uv run --no-sync python -m rag.ingest.parse
"""

import json
import re
from dataclasses import asdict, dataclass, field

from bs4 import BeautifulSoup

from rag.config import PROJECT_ROOT, get_settings

# Parts of the page that are NOT the paper's prose. Removed before we read anything.
JUNK_SELECTORS = [
    ".ltx_bibliography",  # the reference list at the end: lots of text, no answers
    ".ltx_figure",  # figures (images + captions)
    ".ltx_table",  # tables of numbers are hard to search as text; skipped for now
    ".ltx_authors",  # author names and affiliations
    ".ltx_note",  # footnotes, which interrupt sentences mid-way
    ".ltx_ERROR",  # spots where the page generator failed
    "nav",  # menus and the table of contents
    "header",
    "footer",
    "script",
    "style",
    "button",
]


@dataclass
class Section:
    heading: str
    text: str


@dataclass
class Document:
    id: str
    title: str
    sections: list[Section] = field(default_factory=list)

    @property
    def n_chars(self) -> int:
        return sum(len(s.text) for s in self.sections)


def clean_text(text: str) -> str:
    """Collapse the page's line breaks and repeated spaces into single spaces."""
    return re.sub(r"\s+", " ", text).strip()


def parse_html(paper_id: str, html: str, fallback_title: str = "") -> Document:
    """Turn one paper's HTML into a Document: a title plus a list of (heading, text) sections."""
    soup = BeautifulSoup(html, "lxml")

    # Math is stored as complicated markup. Swap each formula for its plain LaTeX source
    # (e.g. "x^2") so the sentence still reads naturally.
    for math in soup.find_all("math"):
        math.replace_with(math.get("alttext", ""))

    title_tag = soup.select_one("h1.ltx_title_document")
    title = clean_text(title_tag.get_text(" ")) if title_tag else fallback_title
    doc = Document(id=paper_id, title=title)

    # The abstract has its own container, so grab it first, then remove it from the page
    # so it isn't read twice.
    abstract = soup.select_one(".ltx_abstract")
    if abstract:
        for heading in abstract.select(".ltx_title"):
            heading.decompose()  # drop the word "Abstract" itself
        text = clean_text(abstract.get_text(" "))
        if text:
            doc.sections.append(Section("Abstract", text))
        abstract.decompose()

    for selector in JUNK_SELECTORS:
        for tag in soup.select(selector):
            tag.decompose()

    # Walk the page top to bottom. A heading starts a new section; paragraphs belong to the
    # most recent heading. Collecting both in one pass keeps them in the right order.
    heading = "Introduction"  # used only if text appears before any heading
    paragraphs: list[str] = []

    def finish_section() -> None:
        if paragraphs:
            doc.sections.append(Section(heading, "\n\n".join(paragraphs)))
            paragraphs.clear()

    for el in soup.select("h2.ltx_title, h3.ltx_title, h4.ltx_title, h5.ltx_title, div.ltx_para"):
        text = clean_text(el.get_text(" "))
        if not text:
            continue
        if el.name == "div":
            paragraphs.append(text)
        else:
            finish_section()
            heading = text
    finish_section()
    return doc


def process_all() -> None:
    settings = get_settings()
    data_dir = PROJECT_ROOT / settings.paths.data_dir
    out_dir = data_dir / "processed"
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((data_dir / "manifest.json").read_text(encoding="utf-8"))

    problems = []
    for entry in manifest:
        html = (data_dir / "raw" / f"{entry['id']}.html").read_text(encoding="utf-8")
        doc = parse_html(entry["id"], html, fallback_title=entry["title"])
        (out_dir / f"{doc.id}.json").write_text(
            json.dumps(asdict(doc), indent=1, ensure_ascii=False), encoding="utf-8"
        )
        # A real paper has several sections and thousands of characters; flag anything smaller.
        if len(doc.sections) < 3 or doc.n_chars < 3000:
            problems.append((doc.id, len(doc.sections), doc.n_chars))

    print(f"Processed {len(manifest)} papers into {out_dir.relative_to(PROJECT_ROOT)}/")
    print(f"{len(problems)} look suspiciously short (<3 sections or <3000 characters):")
    for pid, n_sections, n_chars in problems[:15]:
        print(f"  {pid}: {n_sections} sections, {n_chars} chars")


if __name__ == "__main__":
    process_all()
